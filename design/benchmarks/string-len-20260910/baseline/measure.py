import json, os, pathlib, subprocess, statistics, hashlib
root=pathlib.Path(os.environ.get('ECL_BENCH_OUTPUT', pathlib.Path(__file__).parent)).resolve()
root.mkdir(parents=True, exist_ok=True)
binary=pathlib.Path(os.environ['ECL_BENCH_BINARY']).resolve()
env=dict(os.environ,ECL_WORKERS='1');env.pop('ECL_PATH',None)
lines=[]
def stage(label, body):
    lines.append('clock.now \'tick set '+body+' '+json.dumps(label)+' io.pp tick clock.elapsed io.pp')
lines.append("'cwd \"metal_bands.csv\" fs.read-bytes [] csv.parse-header \'columns set \'names set")
stage('dict construction', "names columns dict.from-lists 'bands set")
stage('first table validation', 'bands table.from-columns pop')
stage('100 warm validations', '100 (bands table.from-columns pop) times')
stage('country grouping', 'bands ["Country"] table.group-by \'groups set')
stage('count reduction', 'bands "Band ID" at groups dict.vals \'count reduce-groups \'counts set')
stage('symbol aggregate', 'bands ["Country"] [["bands" "Band ID" \'count]] table.aggregate \'aggregation set')
stage('quotation aggregate', 'bands ["Country"] [["bands" "Band ID" (len)]] table.aggregate pop')
stage('composite grouping', 'bands ["Country" "Status"] table.group-by pop')
stage('row materialization', 'bands table.rows pop')
lines.append("'cwd \"all_bands_discography.csv\" fs.read-bytes [] csv.parse-header dict.from-lists table.from-columns 'albums set")
stage('join left grouping', 'bands "Band ID" at wrap group-columns \'lg set')
stage('join right grouping', 'albums "Band ID" at wrap group-columns \'rg set')
stage('join distinct lookup', 'rg lg dict.keys [] dict.at-or \'distinct-matches set')
stage('join group lengths', 'lg dict.vals (len) each \'group-lengths set')
stage('join expand matches', 'distinct-matches group-lengths core.where at \'expanded set')
stage('join flatten left indices', 'lg dict.vals raze \'flat-left set')
stage('join grade left indices', 'flat-left grade \'order set')
stage('join reorder matches', 'expanded order at \'matches set')
stage('join match lengths', 'matches (len) each \'match-lengths set')
stage('join left selectors', 'match-lengths core.where \'li set')
stage('join right selectors', 'matches raze \'ri set')
stage('join left gather', 'bands dict.vals li (at) partial each \'lv set')
lines.append('albums ["Album Name" "Type" "Year" "Number of Reviews" "Average Rating"] dict.at \'right-columns set')
stage('join right gather', 'right-columns ri (at) partial each \'rv set')
stage('join output dictionary', 'bands dict.keys ["Album Name" "Type" "Year" "Number of Reviews" "Average Rating"] cat lv rv cat dict.from-lists \'joined set')
lines.append('"join rows" io.pp joined table.height io.pp')
stage('whole join', 'bands albums [["Band ID" "Band ID"]] table.inner-join pop')
script=root/'table-breakdown.ecl';script.write_text('\n'.join(lines)+'\n')
results=[]
for i in range(4):
    r=subprocess.run([str(binary),str(script)],cwd=os.environ['ECL_BENCH_DATA'],env=env,stdin=subprocess.DEVNULL,capture_output=True,text=True,timeout=180)
    print('run',i,'exit',r.returncode,r.stdout,r.stderr[:2000],flush=True)
    assert r.returncode==0
    output=r.stdout.splitlines();results.append(dict(zip(output[::2],map(int,output[1::2]))))
(root/'table-breakdown.json').write_text(json.dumps({'binary_sha256':hashlib.sha256(binary.read_bytes()).hexdigest(),'runs':results,'median':{k:statistics.median(r[k] for r in results[1:]) for k in results[0]}},indent=2))
